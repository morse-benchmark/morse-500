import argparse
import csv
import math
import re
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import matplotlib.pyplot as plt


STEM_PATTERN = re.compile(
    r"^(?P<problem_type>.+)_(?P<difficulty_tag>[A-Za-z]+(?:[A-Za-z]+)*)(?P<difficulty>\d+)$"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Generate a plot of accuracy vs difficulty level per problem type "
            "from eval labels CSV."
        )
    )
    parser.add_argument(
        "--labels-csv",
        type=Path,
        default=Path("eval/eval_output_labels.csv"),
        help="Path to labels CSV generated by eval/label_eval_outputs.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("eval/accuracy_vs_difficulty.png"),
        help="Output image path.",
    )
    parser.add_argument(
        "--model",
        action="append",
        default=[],
        help=(
            "Optional model filter. Can be provided multiple times "
            "(e.g., --model Qwen3-VL-4B-Instruct --model Qwen3-VL-8B-Instruct)."
        ),
    )
    parser.add_argument(
        "--min-points",
        type=int,
        default=-1,
        help="Minimum number of difficulty levels required to include a problem type.",
    )
    parser.add_argument(
        "--max-problem-types",
        type=int,
        default=0,
        help=(
            "Maximum number of problem types to plot (sorted by total examples). "
            "0 means include all."
        ),
    )
    return parser.parse_args()


def parse_stem(question_stem: str) -> Optional[Tuple[str, int]]:
    base = question_stem.split("_seed", 1)[0]
    match = STEM_PATTERN.match(base)
    if not match:
        return None
    return match.group("problem_type"), int(match.group("difficulty"))


def load_rows(labels_csv: Path, model_filters: List[str]) -> List[Dict]:
    rows: List[Dict] = []
    with labels_csv.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("is_correct") not in {"true", "false"}:
                continue
            if model_filters and row.get("model_name") not in model_filters:
                continue

            parsed = parse_stem(row.get("question_stem", ""))
            if parsed is None:
                continue
            problem_type, difficulty = parsed
            is_correct = 1 if row["is_correct"] == "true" else 0

            rows.append(
                {
                    "problem_type": problem_type,
                    "difficulty": difficulty,
                    "is_correct": is_correct,
                }
            )
    return rows


def aggregate(rows: List[Dict]) -> Tuple[Dict[str, Dict[int, float]], Dict[str, int]]:
    counts = defaultdict(lambda: defaultdict(int))
    correct = defaultdict(lambda: defaultdict(int))
    totals_by_problem_type = defaultdict(int)

    for row in rows:
        ptype = row["problem_type"]
        diff = row["difficulty"]
        counts[ptype][diff] += 1
        correct[ptype][diff] += row["is_correct"]
        totals_by_problem_type[ptype] += 1

    acc = defaultdict(dict)
    for ptype, diff_counts in counts.items():
        for diff, n in diff_counts.items():
            acc[ptype][diff] = correct[ptype][diff] / n if n else 0.0

    return acc, totals_by_problem_type


def plot_accuracy(
    acc_by_type: Dict[str, Dict[int, float]],
    totals_by_type: Dict[str, int],
    output_path: Path,
    min_points: int,
    max_problem_types: int,
) -> None:
    selected = []
    for ptype, diff_map in acc_by_type.items():
        if len(diff_map) >= min_points:
            selected.append(ptype)

    selected.sort(key=lambda p: totals_by_type.get(p, 0), reverse=True)
    if max_problem_types > 0:
        selected = selected[:max_problem_types]

    if not selected:
        raise ValueError(
            "No problem types left to plot. Try lowering --min-points or changing filters."
        )

    n = len(selected)
    n_cols = min(4, n)
    n_rows = math.ceil(n / n_cols)

    fig, axes = plt.subplots(
        n_rows,
        n_cols,
        figsize=(n_cols * 4.0, n_rows * 3.1),
        squeeze=False,
        sharey=True,
    )

    for idx, ptype in enumerate(selected):
        row = idx // n_cols
        col = idx % n_cols
        ax = axes[row][col]

        diff_map = acc_by_type[ptype]
        xs = sorted(diff_map.keys())
        ys = [diff_map[x] for x in xs]

        ax.plot(xs, ys, marker="o", linewidth=1.5, markersize=4)
        ax.set_title(ptype, fontsize=9)
        ax.set_ylim(0.0, 1.0)
        ax.grid(True, linestyle="--", alpha=0.35)

        if row == n_rows - 1:
            ax.set_xlabel("Difficulty")
        if col == 0:
            ax.set_ylabel("Accuracy")

    # Hide unused subplot axes in the last row, if any.
    for idx in range(n, n_rows * n_cols):
        row = idx // n_cols
        col = idx % n_cols
        axes[row][col].axis("off")

    fig.suptitle("Accuracy vs Difficulty Level (One Panel per Problem Type)", fontsize=12)
    fig.tight_layout(rect=[0, 0, 1, 0.97])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=220, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    args = parse_args()

    if not args.labels_csv.exists():
        raise FileNotFoundError(f"Labels CSV not found: {args.labels_csv}")

    rows = load_rows(args.labels_csv, args.model)
    if not rows:
        raise ValueError("No rows available after filtering.")

    acc_by_type, totals_by_type = aggregate(rows)
    plot_accuracy(
        acc_by_type=acc_by_type,
        totals_by_type=totals_by_type,
        output_path=args.output,
        min_points=args.min_points,
        max_problem_types=args.max_problem_types,
    )

    n_problem_types = sum(1 for _, diff_map in acc_by_type.items() if len(diff_map) >= args.min_points)
    print(f"Loaded rows: {len(rows)}")
    print(f"Problem types plotted (before --max-problem-types cap): {n_problem_types}")
    print(f"Saved plot to: {args.output}")


if __name__ == "__main__":
    main()
