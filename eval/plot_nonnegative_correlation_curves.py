import argparse
import csv
import math
import re
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import matplotlib.pyplot as plt


STEM_PATTERN = re.compile(
    r"^(?P<problem_type>.+)_(?P<difficulty_tag>[A-Za-z]+(?:_[A-Za-z]+)*)(?P<difficulty>\d+)$"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Compute per-problem-type correlation between difficulty and accuracy, "
            "then plot curves with nonnegative correlation."
        )
    )
    parser.add_argument(
        "--labels-csv",
        type=Path,
        default=Path("eval/eval_output_labels.csv"),
        help="Path to labels CSV generated by eval/label_eval_outputs.py.",
    )
    parser.add_argument(
        "--plot-output",
        type=Path,
        default=Path("eval/accuracy_vs_difficulty_nonnegative_corr.png"),
        help="Output image path for filtered curves.",
    )
    parser.add_argument(
        "--corr-output",
        type=Path,
        default=Path("eval/problem_type_correlations.csv"),
        help="Output CSV path with per-problem-type correlations.",
    )
    parser.add_argument(
        "--model",
        action="append",
        default=[],
        help="Optional model filter. Can be repeated.",
    )
    parser.add_argument(
        "--min-points",
        type=int,
        default=2,
        help="Minimum number of difficulty levels needed to compute correlation.",
    )
    return parser.parse_args()


def parse_stem(question_stem: str) -> Optional[Tuple[str, int]]:
    base = question_stem.split("_seed", 1)[0]
    match = STEM_PATTERN.match(base)
    if not match:
        return None
    return match.group("problem_type"), int(match.group("difficulty"))


def load_rows(labels_csv: Path, model_filters: List[str]) -> List[Tuple[str, int, int]]:
    rows: List[Tuple[str, int, int]] = []
    with labels_csv.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("is_correct") not in {"true", "false"}:
                continue
            if model_filters and row.get("model_name") not in model_filters:
                continue

            parsed = parse_stem(row.get("question_stem", ""))
            if parsed is None:
                continue

            ptype, difficulty = parsed
            is_correct = 1 if row["is_correct"] == "true" else 0
            rows.append((ptype, difficulty, is_correct))
    return rows


def aggregate_accuracy(
    rows: List[Tuple[str, int, int]]
) -> Dict[str, Dict[int, float]]:
    counts = defaultdict(lambda: defaultdict(int))
    correct = defaultdict(lambda: defaultdict(int))

    for ptype, difficulty, is_correct in rows:
        counts[ptype][difficulty] += 1
        correct[ptype][difficulty] += is_correct

    acc = defaultdict(dict)
    for ptype, diff_map in counts.items():
        for difficulty, n in diff_map.items():
            acc[ptype][difficulty] = correct[ptype][difficulty] / n if n else 0.0
    return acc


def pearson_corr(xs: List[float], ys: List[float]) -> float:
    n = len(xs)
    if n < 2:
        return float("nan")

    mean_x = sum(xs) / n
    mean_y = sum(ys) / n

    cov = sum((x - mean_x) * (y - mean_y) for x, y in zip(xs, ys))
    var_x = sum((x - mean_x) ** 2 for x in xs)
    var_y = sum((y - mean_y) ** 2 for y in ys)

    denom = math.sqrt(var_x * var_y)
    if denom == 0:
        return 0.0
    return cov / denom


def compute_correlations(
    acc_by_type: Dict[str, Dict[int, float]],
    min_points: int,
) -> List[Dict[str, object]]:
    out: List[Dict[str, object]] = []
    for ptype in sorted(acc_by_type.keys()):
        difficulty_to_acc = acc_by_type[ptype]
        xs = sorted(difficulty_to_acc.keys())
        ys = [difficulty_to_acc[x] for x in xs]

        if len(xs) < min_points:
            continue

        corr = pearson_corr([float(x) for x in xs], ys)
        out.append(
            {
                "problem_type": ptype,
                "num_difficulty_levels": len(xs),
                "difficulty_levels": ";".join(str(x) for x in xs),
                "accuracies": ";".join(f"{y:.6f}" for y in ys),
                "pearson_corr": corr,
            }
        )
    return out


def write_correlation_csv(rows: List[Dict[str, object]], out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "problem_type",
                "num_difficulty_levels",
                "difficulty_levels",
                "accuracies",
                "pearson_corr",
            ],
        )
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def plot_nonnegative(
    acc_by_type: Dict[str, Dict[int, float]],
    corr_rows: List[Dict[str, object]],
    out_path: Path,
) -> List[str]:
    keep = [
        row["problem_type"]
        for row in corr_rows
        if float(row["pearson_corr"]) >= 0.0
    ]

    if not keep:
        raise ValueError("No problem types with nonnegative correlation found.")

    keep = sorted(keep)
    plt.figure(figsize=(13, 8))
    for ptype in keep:
        diff_map = acc_by_type[ptype]
        xs = sorted(diff_map.keys())
        ys = [diff_map[x] for x in xs]
        plt.plot(xs, ys, marker="o", linewidth=1.6, markersize=4, label=ptype)

    plt.title("Accuracy vs Difficulty (Problem Types with Nonnegative Correlation)")
    plt.xlabel("Difficulty Level")
    plt.ylabel("Accuracy")
    plt.ylim(0.0, 1.0)
    plt.grid(True, linestyle="--", alpha=0.35)
    plt.legend(
        loc="center left",
        bbox_to_anchor=(1.02, 0.5),
        frameon=False,
        fontsize=8,
        title="Problem Type",
        title_fontsize=9,
    )
    plt.tight_layout()

    out_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out_path, dpi=220, bbox_inches="tight")
    plt.close()
    return keep


def main() -> None:
    args = parse_args()

    if not args.labels_csv.exists():
        raise FileNotFoundError(f"Labels CSV not found: {args.labels_csv}")

    rows = load_rows(args.labels_csv, args.model)
    if not rows:
        raise ValueError("No rows available after filtering.")

    acc_by_type = aggregate_accuracy(rows)
    corr_rows = compute_correlations(acc_by_type, min_points=args.min_points)
    if not corr_rows:
        raise ValueError("No problem types had enough points to compute correlation.")

    corr_rows.sort(key=lambda r: float(r["pearson_corr"]), reverse=True)
    write_correlation_csv(corr_rows, args.corr_output)
    kept = plot_nonnegative(acc_by_type, corr_rows, args.plot_output)

    print(f"Loaded rows: {len(rows)}")
    print(f"Correlations written to: {args.corr_output}")
    print(f"Plot written to: {args.plot_output}")
    print(f"Problem types with nonnegative correlation: {len(kept)}")
    for ptype in kept:
        corr = next(float(r["pearson_corr"]) for r in corr_rows if r["problem_type"] == ptype)
        print(f"- {ptype}: {corr:.4f}")


if __name__ == "__main__":
    main()
